import json
import logging

import requests
from django.conf import settings

logger = logging.getLogger(__name__)


class DocumentProcessingError(Exception):
    pass


def validate_flashcards_data(raw_data) -> list[dict]:
    """
    Validate that raw AI output is a list of 1-N items with non-empty string question/answer.
    Handles responses wrapped in dicts (e.g. {"flashcards": [...]}, {"cards": [...]}).
    Raises DocumentProcessingError if invalid.
    """
    items = raw_data
    if isinstance(items, dict):
        for key in ("flashcards", "cards", "questions"):
            if key in items and isinstance(items[key], list):
                items = items[key]
                break
        else:
            for val in items.values():
                if isinstance(val, list):
                    items = val
                    break

    if not isinstance(items, list) or len(items) == 0:
        raise DocumentProcessingError(
            "Invalid flashcard data from AI: expected a non-empty list of flashcards."
        )

    valid_cards = []
    for item in items:
        if not isinstance(item, dict):
            raise DocumentProcessingError(
                "Invalid flashcard item: each item must be an object with question and answer."
            )
        question = item.get("question")
        answer = item.get("answer")
        if (
            not isinstance(question, str)
            or not isinstance(answer, str)
            or not question.strip()
            or not answer.strip()
        ):
            raise DocumentProcessingError(
                "Invalid flashcard item: question and answer must be non-empty strings."
            )
        valid_cards.append({"question": question.strip(), "answer": answer.strip()})

    return valid_cards


